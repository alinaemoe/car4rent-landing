i18n.use(initReactI18next).init({
  fallbackLng: "ru",
  resources: {
    ru: { translation: FALLBACK_RU },
    en: { translation: FALLBACK_EN },
  },
  interpolation: { escapeValue: false },
  detection: {
    order: ["localStorage"],
    caches: ["localStorage"],
  },
});

export async function loadTranslations() {
  try {
    const { fetchTranslations } = await import("./api-client");
    const translations = await fetchTranslations();
    if (translations && Array.isArray(translations)) {
      translations.forEach((t) => {
        Object.entries(t.value).forEach(([lang, val]) => {
          i18n.addResource(lang, "translation", t.key, val as string);
        });
      });
    }
  } catch {
    // silently use fallbacks
  }
}

export function changeLanguage(lng: string) {
  i18n.changeLanguage(lng);
  if (typeof window !== "undefined") {
    localStorage.setItem("i18nextLng", lng);
  }
}

export default i18n;
